const slides = { imapdf: 0, barcodelens: 0, netqguard: 0, prolab: 0, science: 0, masar: 0 };

function showGallery(name, index) {
  const gallery = document.querySelector(`[data-gallery="${name}"]`);
  const images = pics[name]?.[lang] || pics[name]?.en;

  if (!gallery || !images?.length) return;

  const next = ((index % images.length) + images.length) % images.length;
  slides[name] = next;
  const image = gallery.querySelector("img");
  if (!image) return;

  image.src = images[next].startsWith("http") ? images[next] : "assets/" + images[next];
  image.classList.toggle(
    "compact-shot",
    (name === "barcodelens" && next > 0) ||
      name === "netqguard" ||
      name === "prolab" ||
      name === "science" ||
      name === "masar",
  );
  gallery.querySelectorAll(".dots button").forEach((button, number) => {
    button.classList.toggle("active", number === next);
  });
}

function apply() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelector("#lang").textContent =
    lang === "en" ? "العربية" : "English";

  document.querySelectorAll("[data-k]").forEach((element) => {
    const value = tr[lang][element.dataset.k];
    if (value) element.innerHTML = value;
  });

  Object.keys(pics).forEach((name) => showGallery(name, 0));
}

document.querySelector("#lang").onclick = () => {
  lang = lang === "en" ? "ar" : "en";
  apply();
};

document.querySelectorAll(".gallery[data-gallery]").forEach((gallery) => {
  const name = gallery.dataset.gallery;
  gallery.querySelectorAll(".dots button").forEach((button) => {
    button.onclick = () => showGallery(name, Number(button.dataset.i));
  });
});

setInterval(() => {
  Object.keys(pics).forEach((name) => showGallery(name, slides[name] + 1));
}, 4500);

const io = new IntersectionObserver(
  (entries) => {
    entries.forEach(
      (entry) => entry.isIntersecting && entry.target.classList.add("show"),
    );
  },
  { threshold: 0.12 },
);

document.querySelectorAll(".reveal").forEach((element) => io.observe(element));
apply();
