let lang = 'en';

const pics = {
  imapdf: {
    en: ['en-cover.jpg', 'en-1.png', 'en-2.png', 'en-3.png'],
    ar: ['ar-cover.png', 'ar-1.png', 'ar-2.png', 'ar-3.png']
  },
  barcodelens: {
    en: ['barcodelens-cover.png', 'barcodelens-1.jpg', 'barcodelens-2.png', 'barcodelens-3.png'],
    ar: ['barcodelens-cover.png', 'barcodelens-1.jpg', 'barcodelens-2.png', 'barcodelens-3.png']
  },
  netqguard: {
    en: ['netqguard-en-1.jpg', 'netqguard-en-2.jpg', 'netqguard-en-3.jpg', 'netqguard-en-4.jpg'],
    ar: ['netqguard-ar-1.jpg', 'netqguard-ar-2.jpg', 'netqguard-ar-3.jpg', 'netqguard-ar-4.jpg']
  }
};

const slides = { imapdf: 0, barcodelens: 0, netqguard: 0 };

function showGallery(name, index) {
  const gallery = document.querySelector(`[data-gallery="${name}"]`);
  const images = pics[name]?.[lang] || pics[name]?.en;

  if (!gallery || !images?.length) return;

  const next = ((index % images.length) + images.length) % images.length;
  slides[name] = next;
  const image = gallery.querySelector('img');
  if (!image) return;

  image.src = 'assets/' + images[next];
  image.classList.toggle('compact-shot', (name === 'barcodelens' && next > 0) || name === 'netqguard');
  gallery.querySelectorAll('.dots button').forEach((button, number) => {
    button.classList.toggle('active', number === next);
  });
}

function apply() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.querySelector('#lang').textContent = lang === 'en' ? 'العربية' : 'English';

  document.querySelectorAll('[data-k]').forEach(element => {
    const value = tr[lang][element.dataset.k];
    if (value) element.innerHTML = value;
  });

  Object.keys(pics).forEach(name => showGallery(name, 0));
}

document.querySelector('#lang').onclick = () => {
  lang = lang === 'en' ? 'ar' : 'en';
  apply();
};

document.querySelectorAll('.gallery[data-gallery]').forEach(gallery => {
  const name = gallery.dataset.gallery;
  gallery.querySelectorAll('.dots button').forEach(button => {
    button.onclick = () => showGallery(name, Number(button.dataset.i));
  });
});

setInterval(() => {
  Object.keys(pics).forEach(name => showGallery(name, slides[name] + 1));
}, 4500);

const io = new IntersectionObserver(entries => {
  entries.forEach(entry => entry.isIntersecting && entry.target.classList.add('show'));
}, { threshold: .12 });

document.querySelectorAll('.reveal').forEach(element => io.observe(element));
apply();
